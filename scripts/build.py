"""Builds the deployable schedule builder from src/ and data/.

Usage:
    python scripts/build.py

Reads:
    src/index.html, src/styles.css, src/app.js
    data/booth_sections.json, data/law_sections.json, data/details.json
Writes:
    site/   index.html, styles.css, app.js, data.js   (multi-file static site; serve the folder as-is)
    dist/schedule-builder.html                        (one self-contained page with everything inlined)
"""

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def data_script(root: Path) -> str:
    """Returns data.js: section records and pop-up details as window globals read by app.js."""
    sections = []
    for name in ("booth_sections.json", "law_sections.json"):
        sections += json.loads((root / "data" / name).read_text(encoding="utf-8"))
    details = json.loads((root / "data" / "details.json").read_text(encoding="utf-8"))
    body = (
        "// Generated by scripts/build.py from data/*.json. Do not edit by hand.\n"
        f"window.W27_SECTIONS = {json.dumps(sections, ensure_ascii=False, separators=(',', ':'))};\n"
        f"window.W27_DETAILS = {json.dumps(details, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    # "</" would end an inline <script> early in the single-file build; "<\/" means the same in JS.
    return body.replace("</", "<\\/")


def single_file(index_html: str, css: str, data_js: str, app_js: str) -> str:
    """Inlines the stylesheet and both scripts into index.html."""
    replacements = {
        '<link rel="stylesheet" href="styles.css">': f"<style>\n{css}</style>",
        '<script src="data.js"></script>': f"<script>\n{data_js}</script>",
        '<script src="app.js"></script>': f"<script>\n{app_js}</script>",
    }
    for tag, inline in replacements.items():
        if index_html.count(tag) != 1:
            raise ValueError(f"src/index.html must contain {tag!r} exactly once")
        index_html = index_html.replace(tag, inline)
    return index_html


def build(root: Path = ROOT, site_dir: Path | None = None, dist_dir: Path | None = None) -> tuple[Path, Path]:
    """Writes site/ and dist/schedule-builder.html. Returns (site_dir, single_file_path).

    Existing files in site_dir are replaced; other files there are left alone.
    """
    site_dir = site_dir or root / "site"
    dist_dir = dist_dir or root / "dist"
    site_dir.mkdir(parents=True, exist_ok=True)
    dist_dir.mkdir(parents=True, exist_ok=True)
    src = root / "src"
    for name in ("index.html", "styles.css", "app.js"):
        shutil.copyfile(src / name, site_dir / name)
    data_js = data_script(root)
    (site_dir / "data.js").write_text(data_js, encoding="utf-8")
    page = single_file(
        (src / "index.html").read_text(encoding="utf-8"),
        (src / "styles.css").read_text(encoding="utf-8"),
        data_js,
        (src / "app.js").read_text(encoding="utf-8"),
    )
    out = dist_dir / "schedule-builder.html"
    out.write_text(page, encoding="utf-8")
    return site_dir, out


if __name__ == "__main__":
    site, dist = build()
    print(f"Wrote {site.relative_to(ROOT)}/ and {dist.relative_to(ROOT)}")
